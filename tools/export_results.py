#!/usr/bin/env python3
"""Export plots and metrics from standalone NMR-AI teaching runs."""

import argparse
import csv
import hashlib
import json
from pathlib import Path

import numpy as np

from analyze_predictions import load_predictions, summarize
from lineshape import SIMULATOR
from nmr_lab import FREQUENCY, sample_configurations, simulate

ROOT = Path(__file__).resolve().parents[1]
RUNS = [
    ("narrow", "Narrow variation · multiscale CNN", "narrow_multiscale"),
    ("broad", "Broad variation · multiscale CNN", "broad_multiscale"),
    ("compact", "Broad variation · compact CNN", "broad_compact"),
]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--runs-dir", type=Path, default=ROOT / "local-results" / "qmeter")
    args = parser.parse_args()
    runs = []
    for run_id, label, directory in RUNS:
        folder = args.runs_dir / directory
        source = folder / "test_predictions.csv"
        truth, pred = load_predictions(source)
        error = truth - pred
        half_range = max(1e-7, float(np.quantile(np.abs(error), 0.995)) * 1.1)
        bins = np.linspace(-half_range, half_range, 61)
        counts, edges = np.histogram(error, bins=bins)
        local = (truth >= 0.045) & (truth < 0.055)
        with (folder / "history.csv").open(newline="") as stream:
            history = [{key: float(value) for key, value in row.items()} for row in csv.DictReader(stream)]
        with np.load(folder / "scaler.npz") as scaler:
            target_scale = float(scaler["target_scale"][0])
        config = json.loads((folder / "config.json").read_text())
        dataset_file = Path(config["data"])
        if not dataset_file.is_absolute():
            dataset_file = ROOT / dataset_file
        dataset_settings = json.loads(dataset_file.with_suffix(".json").read_text())["settings"]
        if config.get("simulator") != SIMULATOR or dataset_settings.get("simulator") != SIMULATOR:
            raise ValueError("Simulator version mismatch: regenerate data and retrain")
        dataset_settings["output"] = dataset_file.name
        if dataset_settings.get("configurations"):
            dataset_settings["configurations"] = Path(dataset_settings["configurations"]).name
        config["data"] = Path(config["data"]).name
        config["output_dir"] = directory
        runs.append({
            "id": run_id, "label": label, "directory": directory,
            "source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
            "metrics": summarize(truth, pred, 0.05),
            "near_five_percent": summarize(truth[local], pred[local], 0.05),
            "split": json.loads((folder / "split.json").read_text()),
            "config": config,
            "dataset_settings": dataset_settings,
            "history": history, "target_scale": target_scale,
            "histogram": {"edges": edges.tolist(), "counts": counts.tolist(),
                          "outside": int(np.sum((error < edges[0]) | (error > edges[-1])))},
        })
    snapshot = {"dataset": "NMR-AI complex Pake susceptibility coupled to a physical Q-meter circuit",
                "simulator": SIMULATOR,
                "voltage_unit": "V", "residual_definition": "P_true - P_pred",
                "reference_p0": 0.05,
                "note": "Actual runs of the physical forward model with controlled parameter variation, a noisy "
                        "independent baseline reference and ideal TE calibration. Not experimentally fitted deuteron "
                        "parameter distributions, a paper reproduction, or an experimental accuracy measurement. "
                        "Metrics recomputed from prediction CSVs in float64.",
                "runs": runs}
    configuration = sample_configurations(1)[0]
    event = simulate(0.05, configuration, np.random.default_rng(42))
    snapshot["spectrum"] = {
        "label": "Complex spin-1 Pake susceptibility through the Q-meter circuit; P=0.05",
        "simulator": SIMULATOR, "configuration": configuration,
        "p": 0.05, "seed": 42,
        "frequency": FREQUENCY.tolist(),
        **{name: [float(f"{value:.9g}") for value in event[name]]
           for name in ("signal", "baseline", "lineshape", "noise")},
    }
    output = ROOT / "docs" / "assets" / "results.js"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("// Generated by tools/export_results.py; synthetic aggregates only.\n"
                      "window.TUTORIAL_RESULTS = " + json.dumps(snapshot, separators=(",", ":"), allow_nan=False) + ";\n")
    # Keep the no-JavaScript table synchronized with the exact same metrics.
    import html
    import re
    rows = "".join(f"<tr><td>{html.escape(run['label'])}</td><td>{run['metrics']['n']}</td>"
                   + "".join(f"<td>{run['metrics'][key]:.7f}</td>" for key in ("bias", "width", "rmse"))
                   + "</tr>" for run in runs)
    page = ROOT/"docs/index.html"
    page.write_text(re.sub(r'<tbody id="results-table">.*?</tbody>',
                          '<tbody id="results-table">'+rows+'</tbody>', page.read_text(), flags=re.S))
    print(f"Wrote {output.relative_to(ROOT)} ({output.stat().st_size:,} bytes)")


if __name__ == "__main__":
    main()
